  # 유형 요약
  st.markdown(f"### {m_info['title']}")
  st.info(f"✨ **특징:** {m_info['desc']}")

  st.write("---")
  st.subheader(f"🎯 {selected_mbti} 맞춤 추천 직업 TOP 3")

  # 직업 3가지 카드 출력
  for i, job in enumerate(m_info["jobs"], 1):
    with st.container():
      st.markdown(f"#### {i}. {job['name']}")
      st.write(f"👉 **추천 이유:** {job['why']}")
      st.write("")

  st.divider()

  # 상담가 쌤의 따뜻한 응원 메시지
